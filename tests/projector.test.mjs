test('REQ-VIS-001: ProjectorND preserves exact 2D and 3D coordinates when N <= 3', () => {
  const projector = new ProjectorND();

  const p2 = projector.projectNDTo3D([4.5, -7.25]);
  assert.equal(p2.x, 4.5);
  assert.equal(p2.y, -7.25);
  assert.equal(p2.z, 0);
  assert.equal(p2.wDepth, 0);
  assert.equal(p2.effectiveScale, 1.0);
  assert.equal(p2.dimension, 2);

  const p3 = projector.projectNDTo3D([-3.0, 8.0, 5.5]);
  assert.equal(p3.x, -3.0);
  assert.equal(p3.y, 8.0);
  assert.equal(p3.z, 5.5);
  assert.equal(p3.wDepth, 0);
  assert.equal(p3.effectiveScale, 1.0);
  assert.equal(p3.dimension, 3);
});

test('REQ-VIS-001: ProjectorND projects N = 4, 5, 6 hypercubes generated by the Rust WASM core with finite wDepth and scale differentiation', async () => {
  const projector = new ProjectorND({ higherDimProjectionDistance: 12 });
  const universe = await RustWasmUniverse.create(WASM_BYTES, { maxUniverseDimension: 6 });

  for (const dim of [4, 5, 6]) {
    const id = universe.spawnBeing({
      dimension: dim,
      maxDimension: dim,
      family: 'hypercube',
      sides: 4,
      energy: 50
    });
    const snap = universe.getUniverseSnapshot();
    const being = snap.beings.find((b) => b.entityId === id);
    assert.ok(being, `Rust WASM spawned ${dim}D hypercube`);
    assert.equal(being.vertices.length, 1 << dim);

    const projected3D = being.vertices.map((v) => projector.projectNDTo3D(v));
    const projected2D = being.vertices.map((v) =>
      projector.projectNDToScreen(v, 1280, 720)
    );

    let minScale = Infinity;
    let maxScale = -Infinity;
    let minW = Infinity;
    let maxW = -Infinity;

    for (let i = 0; i < projected3D.length; i++) {
      const p3 = projected3D[i];
      const p2 = projected2D[i];

      assert.ok(Number.isFinite(p3.x), `N=${dim} vertex ${i} x is finite`);
      assert.ok(Number.isFinite(p3.y), `N=${dim} vertex ${i} y is finite`);
      assert.ok(Number.isFinite(p3.z), `N=${dim} vertex ${i} z is finite`);
      assert.ok(Number.isFinite(p3.wDepth), `N=${dim} vertex ${i} wDepth is finite`);
      assert.ok(Number.isFinite(p2.u), `N=${dim} vertex ${i} screen u is finite`);
      assert.ok(Number.isFinite(p2.v), `N=${dim} vertex ${i} screen v is finite`);
      assert.equal(p2.visible, true);

      minScale = Math.min(minScale, p3.effectiveScale);
      maxScale = Math.max(maxScale, p3.effectiveScale);
      minW = Math.min(minW, p3.wDepth);
      maxW = Math.max(maxW, p3.wDepth);
    }

    assert.ok(maxScale > minScale, `N=${dim} hypercube inner/outer cells have distinct perspective scale`);
    assert.ok(maxW > minW, `N=${dim} hypercube vertices span positive and negative wDepth`);
  }
});

test('REQ-VIS-001: ProjectorND camera orbit, zoom, and slice offsets transform screen coordinates deterministically', () => {
  const projector = new ProjectorND({
    cameraYaw: 0.5,
    cameraPitch: 0.4,
    cameraDistance: 60,
    fovScale: 500
  });

  const target = [6, 4, 3, 2];
  const before = projector.projectNDToScreen(target, 1000, 800);

  projector.orbit(0.35, 0.15);
  const afterOrbit = projector.projectNDToScreen(target, 1000, 800);
  assert.notEqual(before.u, afterOrbit.u);
  assert.notEqual(before.v, afterOrbit.v);

  const distBeforeZoom = projector.cameraDistance;
  projector.zoom(0.75);
  assert.ok(projector.cameraDistance < distBeforeZoom);
  const afterZoom = projector.projectNDToScreen(target, 1000, 800);
  assert.ok(afterZoom.scale > afterOrbit.scale, 'Zooming in increases projected scale');

  // Slice offset on Z axis (axis 2) shifts 3D Z coordinate
  projector.setSliceOffset(2, 2.5);
  assert.equal(projector.getSliceOffset(2), 2.5);
  const pWithSlice = projector.projectNDTo3D([1, 2, 5]);
  assert.equal(pWithSlice.z, 2.5);
});

test('REQ-VIS-001: ProjectorND Space-Time Worldline Mode maps proper time delta onto the 3D Z axis', () => {
  const projector = new ProjectorND({
    spaceTimeMode: false,
    timeAxisScale: 1.5
  });

  const pos2D = [3.0, -2.0];
  const spatialProj = projector.projectNDTo3D(pos2D, {
    sampleTime: 4.0,
    universalTime: 10.0
  });
  assert.equal(spatialProj.z, 0);

  projector.setSpaceTimeMode(true);
  assert.equal(projector.spaceTimeMode, true);

  const pastSample = projector.projectNDTo3D(pos2D, {
    sampleTime: 4.0,
    universalTime: 10.0
  });
  const presentSample = projector.projectNDTo3D(pos2D, {
    sampleTime: 10.0,
    universalTime: 10.0
  });

  assert.equal(pastSample.x, 3.0);
  assert.equal(pastSample.y, -2.0);
  assert.equal(pastSample.z, (4.0 - 10.0) * 1.5);
  assert.equal(presentSample.z, 0);
  assert.ok(presentSample.z > pastSample.z);
});

test('REQ-VIS-002: SpaceTimeVisualizer.render() and ControlHUD.update() execute full 3D & 2D viewport rendering and DOM telemetry against RustWasmUniverse', async () => {
  const universe = await RustWasmUniverse.create(WASM_BYTES, { maxUniverseDimension: 6 });
  const ids = universe.seedInitialPopulation({ count2D: 6, count3D: 2, count4D: 1 });
  const id5D = universe.spawnBeing({ dimension: 5, maxDimension: 5, family: 'hypercube' });
  const id6D = universe.spawnBeing({ dimension: 6, maxDimension: 6, family: 'orthoplex' });
  universe.triggerRandomInjection(3, 2);
  universe.stepTicks(30);

  // Create stateful 2D Canvas rendering context harnesses that record all draw calls
  const makeCanvasHarness = (width, height) => {
    const ops = [];
    const ctx = {
      fillStyle: '',
      strokeStyle: '',
      lineWidth: 1,
      globalAlpha: 1,
      font: '',
      setTransform: (...args) => ops.push(['setTransform', ...args]),
      createRadialGradient: () => ({ addColorStop: () => {} }),
      createLinearGradient: () => ({ addColorStop: () => {} }),
      fillRect: (...args) => ops.push(['fillRect', ...args]),
      save: () => ops.push(['save']),
      restore: () => ops.push(['restore']),
      beginPath: () => ops.push(['beginPath']),
      closePath: () => ops.push(['closePath']),
      moveTo: (...args) => ops.push(['moveTo', ...args]),
      lineTo: (...args) => ops.push(['lineTo', ...args]),
      stroke: () => ops.push(['stroke']),
      fill: () => ops.push(['fill']),
      arc: (...args) => ops.push(['arc', ...args]),
      setLineDash: (...args) => ops.push(['setLineDash', ...args]),
      fillText: (...args) => ops.push(['fillText', ...args])
    };
    return {
      width,
      height,
      clientWidth: width,
      clientHeight: height,
      ops,
      addEventListener: () => {},
      getBoundingClientRect: () => ({ left: 0, top: 0, width, height }),
      getContext: (type) => (type === '2d' ? ctx : null)
    };
  };

  const canvas3D = makeCanvasHarness(1280, 720);
  const canvas2D = makeCanvasHarness(420, 320);

  // Create stateful DOM elements harness for ControlHUD.update()
  const domElements = new Map();
  const getEl = (sel) => {
    if (!domElements.has(sel)) {
      domElements.set(sel, {
        textContent: '',
        innerHTML: '',
        style: {},
        classList: { toggle: () => {} },
        addEventListener: () => {},
        querySelectorAll: () => []
      });
    }
    return domElements.get(sel);
  };
  const domRoot = {
    querySelector: (sel) => getEl(sel),
    querySelectorAll: () => []
  };

  const projector = new ProjectorND({ spaceTimeMode: true });
  const visualizer = new SpaceTimeVisualizer({
    universe,
    canvas3D,
    canvas2D,
    projector
  });
  const hud = new ControlHUD({ universe, visualizer, root: domRoot });

  visualizer.setSliceZ(0.0);
  visualizer.selectEntity(id6D);
  assert.equal(visualizer.selectedEntityId, id6D);

  // Execute full 3D and 2D viewport render pass and HUD telemetry update
  visualizer.render();
  hud.update();

  assert.ok(canvas3D.ops.length > 50, '3D viewport executed canvas draw operations');
  assert.ok(canvas2D.ops.length > 20, '2D slice viewport executed canvas draw operations');
  assert.ok(visualizer._hitTargets3D.length >= ids.length + 2, '3D hit targets populated for all beings');
  assert.ok(visualizer._hitTargets2D.length >= 1, '2D slice hit targets populated for 2D & sliced beings');
  assert.ok(getEl('#stat-proper-time').textContent.endsWith('s'));
  assert.ok(getEl('#inspector-content').innerHTML.includes(`Entity #${id6D}`));

  // Verify REQ-PERF-001: diff-guarded inspector update does not overwrite container.innerHTML when structural state is unchanged
  const sentinelHtml = getEl('#inspector-content').innerHTML + '<!-- SENTINEL -->';
  getEl('#inspector-content').innerHTML = sentinelHtml;
  universe.stepTicks(1);
  hud.update();
  assert.ok(
    getEl('#inspector-content').innerHTML.endsWith('<!-- SENTINEL -->'),
    'Inspector DOM is preserved across ticks when structural signature is unchanged'
  );
});
